#!/usr/bin/env node
// Pull real building data for every pizzeria in a neighborhood and write src/data/lots/<hood>.ts.
//
//   pnpm lots village
//
// For each place: NYC GeoSearch (address → tax lot), PLUTO (floors, frontage, depth, building class,
// year built, corner lot) for the pizzeria's lot and its neighbours on the same street and block,
// and NYC Building Footprints (roof height). NYC only; Hoboken would need OpenStreetMap instead.
// All three APIs are public and keyless.
import { writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PLACES } from '../src/data/places.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NEIGHBOURS = 3; // lots kept on each side of the pizzeria's lot
const hood = process.argv[2];
const places = PLACES.filter(p => p.hood === hood);
if (!places.length) { console.error('usage: pnpm lots <hood>   (a hood id from src/data/places.ts)'); process.exit(1); }
if (places.some(p => !/, (New York|Brooklyn|Bronx|Queens|Staten Island), NY/.test(p.address))) {
  console.error(`${hood}: only NYC addresses are supported (PLUTO).`); process.exit(1);
}

async function get(url) {
  const r = await fetch(url, { headers: { accept: 'application/json' } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
}
const soda = (dataset, where, select) =>
  get(`https://data.cityofnewyork.us/resource/${dataset}.json?` + new URLSearchParams({ $where: where, ...(select && { $select: select }), $limit: '500' }));
const num = v => (v == null || v === '' ? null : Number(v));
const houseNo = addr => { const m = /^(\d+)([A-Z]?)/.exec(addr); return m ? Number(m[1]) + (m[2] ? (m[2].charCodeAt(0) - 64) / 100 : 0) : Infinity; };
const streetOf = addr => addr.replace(/^[\d-]+[A-Z]? /, '');

const out = {};
for (const p of places) {
  const geo = await get('https://geosearch.planninglabs.nyc/v2/search?' + new URLSearchParams({ text: p.address, size: '1' }));
  const g = geo.features[0]?.properties;
  const bbl = g?.addendum?.pad?.bbl;
  if (!bbl) throw new Error(`could not geocode ${p.address}`);
  const [lot] = await soda('64uk-42ks', `bbl=${bbl}`);
  const street = g.street.toUpperCase();

  // every lot on the same block whose address is on the storefront's street, in house-number order
  const block = await soda('64uk-42ks', `borough='${lot.borough}' AND block=${Number(lot.block)}`,
    'address,bbl,numfloors,lotfront,lotdepth,bldgfront,bldgdepth,bldgclass,yearbuilt,lottype');
  const face = block.filter(l => streetOf(l.address) === street || l.bbl === lot.bbl)
    .sort((a, b) => houseNo(a.address) - houseNo(b.address));
  const i = face.findIndex(l => l.bbl === lot.bbl);
  const win = face.slice(Math.max(0, i - NEIGHBOURS), i + NEIGHBOURS + 1);

  const fp = await soda('5zhs-2jue', `mappluto_bbl in (${win.map(l => `'${Math.round(l.bbl)}'`).join(',')})`, 'mappluto_bbl,height_roof');
  const roof = {};
  for (const f of fp) roof[f.mappluto_bbl] = Math.max(roof[f.mappluto_bbl] ?? 0, Number(f.height_roof) || 0);

  out[p.id] = {
    street,
    lots: win.map(l => ({
      addr: l.address,
      front: num(l.bldgfront) || num(l.lotfront),
      depth: num(l.bldgdepth) || num(l.lotdepth),
      floors: num(l.numfloors),
      roof: roof[String(Math.round(l.bbl))] ? Math.round(roof[String(Math.round(l.bbl))] * 10) / 10 : null,
      year: num(l.yearbuilt) || null,
      cls: l.bldgclass,
      corner: l.lottype === '3',
      ...(l.bbl === lot.bbl && { place: true }),
    })),
  };
  console.log(`${p.id}: ${lot.address} + ${win.length - 1} neighbours on ${street}`);
}

const file = resolve(ROOT, `src/data/lots/${hood}.ts`);
await mkdir(dirname(file), { recursive: true });
await writeFile(file, `// Generated by \`pnpm lots ${hood}\` from NYC PLUTO + Building Footprints. Do not edit by hand.
// Lots are in house-number order along each pizzeria's street; \`place: true\` marks the pizzeria's lot.
import type { BlockFace } from '../lots';

export default {
${Object.entries(out).map(([id, f]) => `  ${id}: {\n    street: ${JSON.stringify(f.street)},\n    lots: [\n${f.lots.map(l => `      ${JSON.stringify(l).replace(/"([a-z]+)":/g, '$1: ').replace(/,(?=[a-z]+:)/g, ', ')},`).join('\n')}\n    ],\n  },`).join('\n')}
} satisfies Record<string, BlockFace>;
`);
console.log('wrote', file);
